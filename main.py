from telegram.ext import ApplicationBuilder,CommandHandler,CallbackQueryHandler,MessageHandler,filters
import threading, provisioner
import config,database as db,handlers
import webpanel

def main():
    if not config.BOT_TOKEN: raise SystemExit("LANDING_BOT_TOKEN is missing")
    if not config.ADMIN_ID: raise SystemExit("LANDING_ADMIN_ID is missing")
    db.init_db()
    provisioner.resume_running()
    threading.Thread(target=provisioner.monitor_running,daemon=True).start()
    webpanel.start_webpanel_thread()
    app=ApplicationBuilder().token(config.BOT_TOKEN).build()
    app.add_handler(CommandHandler("start",handlers.start))
    app.add_handler(CommandHandler("admin",handlers.admin))
    app.add_handler(CommandHandler("create_token",handlers.create_token_cmd))
    app.add_handler(CommandHandler("bots",handlers.bots_cmd))
    app.add_handler(CommandHandler("revoke",handlers.revoke))
    app.add_handler(CommandHandler("remove",handlers.remove_cmd))
    app.add_handler(CommandHandler("redeem",handlers.redeem_cmd))
    app.add_handler(CommandHandler("removep",handlers.removep_cmd))
    app.add_handler(CommandHandler("help",handlers.help_cmd))
    app.add_handler(CallbackQueryHandler(handlers.create_bot_cb,pattern="^create_bot$"))
    app.add_handler(CallbackQueryHandler(handlers.mybots,pattern="^mybots$"))
    app.add_handler(CallbackQueryHandler(handlers.profile_cb,pattern="^profile$"))
    app.add_handler(CallbackQueryHandler(handlers.remove_list_cb,pattern="^remove_list$"))
    app.add_handler(CallbackQueryHandler(handlers.remove_confirm_cb,pattern="^remove_confirm_\\d+$"))
    app.add_handler(CallbackQueryHandler(handlers.remove_do_cb,pattern="^remove_do_\\d+$"))
    app.add_handler(CallbackQueryHandler(handlers.redeem_cb,pattern="^redeem$"))
    app.add_handler(CallbackQueryHandler(handlers.contact_cb,pattern="^contact$"))
    app.add_handler(CallbackQueryHandler(handlers.support_reply_cb,pattern="^support_reply_\\d+$"))
    app.add_handler(CallbackQueryHandler(handlers.home_cb,pattern="^home$"))
    app.add_handler(CallbackQueryHandler(handlers.admin_cb,pattern="^a_"))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND,handlers.text_input))
    media_filter=(filters.PHOTO|filters.VIDEO|filters.Document.ALL|filters.AUDIO|filters.VOICE|filters.VIDEO_NOTE|filters.ANIMATION)
    app.add_handler(MessageHandler(media_filter,handlers.media_input))
    print("Father Bot running...")
    app.run_polling()
if __name__=="__main__": main()
